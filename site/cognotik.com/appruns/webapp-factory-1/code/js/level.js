/**
 * Build the World 1-1 level definition.
 * Returns { grid, entities, startCol, startRow }
 */
export function buildLevel1_1() {
  // Deep-copy the base grid
  const grid = WORLD_1_1_ROWS.map(row => [...row]);

  // ── Place tiles manually ──────────────────────────────────

  // Ground gap 1 (cols 75–80)
   for (let c = 75; c <= 80; c++) grid[11][c] = TILE.EMPTY;

  // Ground gap 2 (cols 86–88)
   for (let c = 86; c <= 88; c++) grid[11][c] = TILE.EMPTY;

  // Ground gap 3 (cols 146–149)
   for (let c = 146; c <= 149; c++) grid[11][c] = TILE.EMPTY;

  // Ground gap 4 (cols 157–160)
   for (let c = 157; c <= 160; c++) grid[11][c] = TILE.EMPTY;

  // ── Blocks row (row 8) ────────────────────────────────────
  // First Q block (mushroom)
  grid[8][16] = Q;
  // Brick, Q, Brick, Q, Brick
  grid[8][20] = B;
  grid[8][21] = Q;
  grid[8][22] = B;
  grid[8][23] = Q;  // multi-coin
  grid[8][24] = B;

  // High Q block (row 4, col 22) — star
  grid[4][22] = Q;

  // Bricks row (row 6)
  for (let c = 78; c <= 82; c++) grid[6][c] = B;
  grid[6][78] = Q;

  // More bricks
  for (let c = 91; c <= 96; c++) grid[6][c] = B;
  grid[6][91] = Q;
  grid[6][94] = Q;

  // Upper bricks (row 4)
  for (let c = 91; c <= 96; c++) grid[4][c] = B;

  // Staircase up (cols 134–141, rows 7–11)
  for (let step = 0; step < 4; step++) {
    const col = 134 + step;
    for (let r = 11 - step; r <= 11; r++) grid[r][col] = S;
  }
  // Staircase down (cols 142–149)
  for (let step = 0; step < 4; step++) {
    const col = 142 + step;
    for (let r = 8 + step; r <= 11; r++) grid[r][col] = S;
  }

  // Final staircase (cols 198–205)
  for (let step = 0; step < 8; step++) {
    const col = 198 + step;
    for (let r = 11 - step; r <= 11; r++) grid[r][col] = S;
  }

  // ── Pipes ─────────────────────────────────────────────────
  // Pipe 1 (col 28–29, height 2)
  grid[10][28] = PL; grid[10][29] = PR;
  grid[11][28] = BL; grid[11][29] = BR;

  // Pipe 2 (col 38–39, height 3)
  grid[9][38]  = PL; grid[9][39]  = PR;
  grid[10][38] = BL; grid[10][39] = BR;
  grid[11][38] = BL; grid[11][39] = BR;

  // Pipe 3 (col 46–47, height 4)
  grid[8][46]  = PL; grid[8][47]  = PR;
  grid[9][46]  = BL; grid[9][47]  = BR;
  grid[10][46] = BL; grid[10][47] = BR;
  grid[11][46] = BL; grid[11][47] = BR;

  // Pipe 4 (col 57–58, height 4)
  grid[8][57]  = PL; grid[8][58]  = PR;
  grid[9][57]  = BL; grid[9][58]  = BR;
  grid[10][57] = BL; grid[10][58] = BR;
  grid[11][57] = BL; grid[11][58] = BR;

  // ── Flag pole (col 198) ───────────────────────────────────
  for (let r = 3; r <= 10; r++) grid[r][197] = F;
  grid[11][197] = FB;

  // ── Castle (cols 200–205) ─────────────────────────────────
  // Simple solid blocks for castle
  for (let r = 8; r <= 11; r++) {
    for (let c = 200; c <= 205; c++) grid[r][c] = S;
  }
  // Battlements
  grid[7][200] = S; grid[7][202] = S; grid[7][204] = S;

  // ── Coins in air ─────────────────────────────────────────
  grid[7][11] = C;
  grid[7][12] = C;
  grid[7][13] = C;

  // ── Decorative tiles ─────────────────────────────────────
  // Clouds (row 1)
  grid[1][6]  = dCL; grid[1][7]  = dCM; grid[1][8]  = dCR;
  grid[1][24] = dCL; grid[1][25] = dCM; grid[1][26] = dCR;
  grid[1][56] = dCL; grid[1][57] = dCM; grid[1][58] = dCR;

  // Hills (row 10)
  grid[10][0]  = dHL; grid[10][1]  = dHM; grid[10][2]  = dHR;
  grid[10][16] = dHL; grid[10][17] = dHM; grid[10][18] = dHR;

  // Bushes (row 10)
  grid[10][6]  = dBL; grid[10][7]  = dBM; grid[10][8]  = dBR;
  grid[10][24] = dBL; grid[10][25] = dBM; grid[10][26] = dBR;

  // ── Entity spawn list ─────────────────────────────────────

   const entities = [
    // Goombas
    { type: ENTITY_TYPE.GOOMBA, col: 22, row: 10 },
    { type: ENTITY_TYPE.GOOMBA, col: 23, row: 10 },
    { type: ENTITY_TYPE.GOOMBA, col: 37, row: 10 },
    { type: ENTITY_TYPE.GOOMBA, col: 50, row: 10 },
    { type: ENTITY_TYPE.GOOMBA, col: 51, row: 10 },
    { type: ENTITY_TYPE.GOOMBA, col: 63, row: 10 },
    { type: ENTITY_TYPE.GOOMBA, col: 78, row: 5  },
    { type: ENTITY_TYPE.GOOMBA, col: 79, row: 5  },
    { type: ENTITY_TYPE.GOOMBA, col: 90, row: 10 },
    { type: ENTITY_TYPE.GOOMBA, col: 91, row: 10 },
    { type: ENTITY_TYPE.GOOMBA, col: 100,row: 10 },
    { type: ENTITY_TYPE.GOOMBA, col: 101,row: 10 },
    // Koopas
    { type: ENTITY_TYPE.KOOPA,  col: 30, row: 10 },
    { type: ENTITY_TYPE.KOOPA,  col: 60, row: 10 },
    { type: ENTITY_TYPE.KOOPA,  col: 110,row: 10 },
  ];

  // Question block contents (col → powerup type)
  const questionContents = {
    16: ENTITY_TYPE.MUSHROOM,   // first Q block
     21: ENTITY_TYPE.COIN_POPUP,
     23: ENTITY_TYPE.COIN_POPUP,   // multi-coin
    22: ENTITY_TYPE.STAR,       // high Q block (row 4)
     78: ENTITY_TYPE.COIN_POPUP,
    91: ENTITY_TYPE.MUSHROOM,
     94: ENTITY_TYPE.COIN_POPUP,
  };

  return {
    grid,
    entities,
    questionContents,
    startCol: 3,
    startRow: 10,
    name: 'World 1-1',
    timeLimit: 400,
  };
}

